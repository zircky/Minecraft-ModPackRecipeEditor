package dev.recipeeditor.exporters;

import dev.recipeeditor.recipeengine.editor.*;
import java.util.*;

/** KubeJS 2001 API: lossless JSON through event.custom, with exact-ID removal only. */
public final class KubeJsJavaScriptExporter implements RecipeExporter {
    @Override public ExportFormat format(){return ExportFormat.KUBEJS;}
    @Override public ExportCapability checkCapability(final RecipeChange change,final ExportContext context){
        final String version=new KubeJsCompatibility().check(context);if(!version.isEmpty())return ExportCapability.unsupported(version);
        final String error=new VanillaExportSupport().checkKubeJs(change,context);
        if(error.isEmpty())return ExportCapability.supported("JavaScript: exact-ID remove for UPDATE/DELETE; lossless event.custom(JSON).id for Vanilla serializers. Other scripts can override/remove the result.");
        if(!context.modVersion("kubejs").equals("2001.6.4-build.120"))return ExportCapability.unsupported(error+"; custom/GT codecs are not verified with this KubeJS build");
        if(new Gtceu714Adapter().recognizes(change,context))return new Gtceu714Adapter().check(change,context);
        return ExportCapability.unsupported(error);
    }
    public String targetFile(final ExportContext context){return "kubejs/server_scripts/recipe_editor_"+context.profile().id()+"_generated.js";}
    @Override public Map<String,String> generate(final List<RecipeChange> changes,final ExportContext context){
        if(changes.isEmpty())return Map.of();
        final var text=new ExportText();final var script=new StringBuilder("// Generated by Minecraft Recipe Editor. Review script/load order; runtime validation required.\nServerEvents.recipes(event => {\n");
        for(final var change:changes.stream().sorted(Comparator.comparing(c->c.id().toString())).toList()){
            if(!checkCapability(change,context).supported())throw new IllegalArgumentException("Unsupported KubeJS JavaScript operation: "+change.id());
            if(change.type()!=RecipeChangeType.DELETE&&new Gtceu714Adapter().recognizes(change,context)){
                final var model=new dev.recipeeditor.integrations.gregtech.GregTechRecipeMapper().map(change.replacement().getFirst());
                script.append(new dev.recipeeditor.integrations.gregtech.GregTechRecipeExporter().generate(model,change.id().toString(),change.type()!=RecipeChangeType.CREATE));continue;
            }
            if(change.type()!=RecipeChangeType.CREATE)script.append("  event.remove({id: ").append(text.quote(change.id().toString())).append("});\n");
            if(change.type()!=RecipeChangeType.DELETE)script.append("  event.custom(JSON.parse(").append(text.quote(change.replacement().getFirst().rawJson())).append(")).id(").append(text.quote(change.id().toString())).append(");\n");
        }
        return Map.of(targetFile(context),script.append("});\n").toString());
    }
}
