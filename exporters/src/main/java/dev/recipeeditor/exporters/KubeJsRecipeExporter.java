package dev.recipeeditor.exporters;

import dev.recipeeditor.recipeengine.editor.*;
import java.util.*;
public final class KubeJsRecipeExporter implements RecipeExporter {
    @Override public ExportFormat format(){return ExportFormat.KUBEJS;}
    @Override public ExportCapability checkCapability(final RecipeChange change,final ExportContext context) {
        if(!context.modVersion("kubejs").equals("2001.6.4-build.120"))return ExportCapability.unsupported("KubeJS API is verified only for exact 2001.6.4-build.120; installed="+context.modVersion("kubejs"));
        final String error=new VanillaExportSupport().check(change,context);
        if(error.isEmpty())return ExportCapability.supported("Known Vanilla serializer: exact-ID remove (UPDATE/DELETE) and custom JSON addition. External script ordering remains runtime-dependent.");
        if(context.modpack().minecraftVersion().value().equals("1.20.1")&&context.modpack().loader().type()==dev.recipeeditor.core.importing.ModLoaderType.FORGE&&new Gtceu714Adapter().recognizes(change,context))return new Gtceu714Adapter().check(change,context);
        return ExportCapability.unsupported(error);
    }
    @Override public Map<String,String> generate(final List<RecipeChange> changes,final ExportContext context) {
        if(changes.isEmpty())return Map.of();final var text=new ExportText();final var script=new StringBuilder("// Generated by Minecraft Recipe Editor. Review script/load order; runtime validation required.\nServerEvents.recipes(event => {\n");
        for(final var change:changes.stream().sorted(Comparator.comparing(c->c.id().toString())).toList()) {
            if(!checkCapability(change,context).supported())throw new IllegalArgumentException("Unsupported KubeJS operation");
            if(change.type()!=RecipeChangeType.DELETE && new Gtceu714Adapter().recognizes(change,context)) {
                final var model=new dev.recipeeditor.integrations.gregtech.GregTechRecipeMapper().map(change.replacement().getFirst());
                script.append(new dev.recipeeditor.integrations.gregtech.GregTechRecipeExporter().generate(model,change.id().toString(),change.type()!=RecipeChangeType.CREATE));
                continue;
            }
            if(change.type()!=RecipeChangeType.CREATE)script.append("  event.remove({id: ").append(text.quote(change.id().toString())).append("});\n");
            if(change.type()!=RecipeChangeType.DELETE)script.append("  event.custom(JSON.parse(").append(text.quote(change.replacement().getFirst().rawJson())).append(")).id(").append(text.quote(change.id().toString())).append(");\n");
        }
        script.append("});\n");return Map.of("kubejs/server_scripts/recipe_editor_"+context.profile().id()+"_generated.js",script.toString());
    }
}
